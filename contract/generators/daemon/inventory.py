def generate_inventory(contract: ContractView) -> str:
    daemon = {operation.name for operation in contract.operations if operation.daemon_only}
    partial = ai_bindings()
    groups = [set(MIGRATED), set(MANUAL), set(partial)]
    if any(groups[a] & groups[b] for a in range(len(groups)) for b in range(a + 1, len(groups))):
        raise Unsupported("daemon boundary inventory contains duplicate dispositions")
    known = set.union(*groups)
    if daemon != known:
        raise Unsupported(
            f"daemon boundary inventory differs: missing={sorted(daemon - known)}, stale={sorted(known - daemon)}"
        )
    http = {binding.operation: binding for binding in contract.http}
    if daemon - http.keys():
        raise Unsupported(f"daemon boundary inventory has operations without HTTP: {sorted(daemon - http.keys())}")
    lines = [
        "<!-- Generated by compiler from the contract and daemon boundary inventory. Do not edit. -->",
        "# Daemon boundary inventory",
        "",
        ("This inventory covers every declared daemon-only operation. Core-backed HTTP operations use "
        "`ContractRoutes.h` and `ContractJson.h`; their implementation remains in core. "
        "Runtime authentication and connection ownership remain outside generated dispatch."),
        "",
        (f"Current dispositions: {len(MIGRATED)} complete, {len(partial)} partially generated AI boundaries, "
        f"{len(MANUAL)} remaining handwritten boundaries."),
        "",
        "## Next bounded migrations for everyday Desktop use",
        "",
        ("1. Generate the project checkpoint/change-stream boundary (`get_event_cursor`, `stream_changes`) "
        "when changing remote card refresh. Desktop's `services/presence_stream.vala` consumes `/events`; "
        "preserve replay/cursor and named-event semantics."),
        ("2. Review health/bye lifecycle boundaries when changing Desktop startup, failure handling or shutdown. "
        "Current consumers are `services/api_client/health.vala` and `services/presence_stream.vala`."),
        ("3. Finish location list/preference/delete-binding boundaries when changing the storage UI, reusing "
        "the proven record codecs. `services/api_client/resources.vala` consumes the location workflow; "
        "provider probes and OAuth stay in runtime services. Attachment import/download follows when needed."),
        "",
        ("Card create/read/update/list/trash/move/restore and project pull/push/sync already use the generated "
        "core boundary. Desktop's full-sync behavior remains separate application/runtime work. "
        "AI, catalogs, documentation and unrelated domains remain under #390."),
        "",
        "## Complete boundaries",
        "",
        ("Public record fields, handler parameter declarations, route/parameter validation, success encoding "
        "and error response fields are generated from the compiler result. Runtime services, handler names, "
        "exception-to-status bindings and compatibility diagnostic wording are backend data."),
        "",
        "| Operation | HTTP | Runtime handler | Services |",
        "| --- | --- | --- | --- |",
    ]
    for name, wiring in bindings().items():
        binding = http[name]
        lines.append(
            f"| `{name}` | `{binding.method} {binding.path}` | `{wiring.handler}` | {', '.join(wiring.services)} |"
        )
    lines += [
        "",
        "## Remaining handwritten boundaries",
        "",
        ("Routing and the listed checks/serialization are in `daemon/src/api/GeneratedRoutes.cpp`; "
        "the handler column identifies the runtime implementation. Error mapping is still shared/handwritten "
        "for these operations. This explicit list does not claim they are covered by the complete generator."),
        "",
        "| Operation | HTTP | Runtime handler in daemon/src/api | Remaining boundary work |",
        "| --- | --- | --- | --- |",
    ]
    for name, (handler, remaining) in MANUAL.items():
        binding = http[name]
        lines.append(f"| `{name}` | `{binding.method} {binding.path}` | `{handler}` | {remaining} |")
    lines += [
        "",
        "## Partially generated AI boundaries",
        "",
        ("`AiRoutes.h` and `AiJson.h` generate dispatch and codecs, with handwritten runtime types in "
        "`AiRuntime.h` and the handlers' headers. Unknown-field checking, schema constraints, response/status "
        "conventions and runtime type agreement still need a per-operation completion review. "
        "Existing generation is preserved in this slice."),
        "",
        "| Operation | HTTP | Runtime handler in holder::api | Services |",
        "| --- | --- | --- | --- |",
    ]
    for name, wiring in partial.items():
        binding = http[name]
        lines.append(f"| `{name}` | `{binding.method} {binding.path}` | `{name}` | {', '.join(wiring.services)} |")
    return "\n".join([*lines, ""])
